"""Compile audited path-only SVGs into inert data. Never import executable SVG markup."""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
assets = {}
for name in ("rabbit", "car"):
    source = root / "assets/whiteboard/fluent" / (name + ".svg")
    svg = ET.parse(source).getroot()
    assert svg.tag == "{http://www.w3.org/2000/svg}svg"
    assert svg.attrib["viewBox"] == "0 0 32 32"
    paths = []
    for child in svg:
        assert child.tag == "{http://www.w3.org/2000/svg}path"
        assert set(child.attrib) <= {"d", "fill", "fill-rule", "clip-rule"}
        assert len(child) == 0
        assert re.fullmatch(r"[MmZzLlHhVvCcSsQqTtAaEe0-9.,+\-\s]+", child.attrib["d"])
        assert re.fullmatch(r"#[0-9a-fA-F]{6}|white", child.attrib["fill"])
        assert child.get("fill-rule", "nonzero") in ("nonzero", "evenodd")
        paths.append(dict(child.attrib))
    assets[name] = paths
output = "// Generated by scripts/build-whiteboard-assets.py; Microsoft MIT artwork, see assets/whiteboard/fluent/LICENSE.\nexport const compiledAssets = " + json.dumps(assets, ensure_ascii=True, indent=2) + ";\n"
destination = root / "src/whiteboard/compiledAssets.js"
if "--check" in sys.argv:
    assert destination.read_text() == output, "Rebuild whiteboard assets"
else:
    destination.write_text(output)
print("Two audited path-only assets verified")
